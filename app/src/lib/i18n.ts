/** Labels with a value in them: "Top rated in {x}". */
const AR_PATTERNS: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^Top rated in (.+)$/, (m) => `الأعلى تقييماً في ${m[1]}`],
  [/^Trending in (.+)$/, (m) => `الرائج في ${m[1]}`],
  [/^Barbers in (.+)$/, (m) => `حلاقون في ${m[1]}`],
  [/^Book a shop in (.+)$/, (m) => `احجز صالوناً في ${m[1]}`],
  [/^Last month's top 10 in (.+)$/, (m) => `أفضل 10 الشهر الماضي في ${m[1]}`],
  [/^In (.+)$/, (m) => `في ${m[1]}`],
  [/^(\d+) reviews$/, (m) => `${m[1]} تقييم`],
  [/^Book · (.+)$/, (m) => `احجز · ${m[1]}`],
  [/^Message (.+)$/, (m) => `راسل ${m[1]}`],
];

/** The Arabic for a label when Arabic is on (else the label itself). */
export function tr(s: string): string {
  if (!isArabic) return s;
  const exact = AR[s];
  if (exact) return exact;
  for (const [re, fn] of AR_PATTERNS) {
    const m = s.match(re);
    if (m) return fn(m);
  }
  return s;
}
